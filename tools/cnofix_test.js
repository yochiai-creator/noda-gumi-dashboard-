console.log('■ 本数の少ない直しの判定（揺れない ≠ 正しい）');
{
  const V = (now, a, b, qty) => s.shipact_smallVerdict_(now,
    [{ 範囲: a[0], 本数: a[1] }, { 範囲: b[0], 本数: b[1] }], qty);
  // 524行目 26-60602：1回きりの読みで 25025〜25026 と書いていた
  let v = V('25025〜25026', ['25025〜25025', 1], ['25025〜25025', 1], 2);
  chk('★2回とも今と別の値なら書き換える候補にする', v.書く === true, v);
  chk('理由を言う', /1回きりの化けた読み/.test(v.判定), v.判定);

  // 50336：2回とも今と同じで数量とも合う
  v = V('20644〜20644', ['20644〜20644', 1], ['20644〜20644', 1], 1);
  chk('2回とも今と同じ・数量とも合う', v.書く === false && /数量とも合う/.test(v.判定), v);

  // 521行目：2回とも同じだが数量5に対して1本＝正しいとは言えない
  v = V('48914〜48914', ['48914〜48914', 1], ['48914〜48914', 1], 5);
  chk('★揺れなくても数量と合わなければ「正しい」と言わない',
    v.書く === false && /数量と合わない/.test(v.判定), v.判定);

  // 2回で違う
  v = V('1〜2', ['1〜2', 2], ['1〜3', 3], 2);
  chk('2回で違えば人に回す、書かない', v.書く === false && /揺れる/.test(v.判定), v);
  v = V('1〜2', ['読めず', null], ['読めず', null], 2);
  chk('読めなければ書かない', v.書く === false, v);
}

console.log('■ 読み直しで数量を変えない');
{
  /* ★ 524行目 26-60602：範囲を直したときに数量まで上書きして 2本→1本 になった。
       本文の「◯本」が読めなかった回に、範囲から数えた本数が入ったため。 */
  const Q = (old, f) => s.shipact_recheckQty_(old, f);
  let p = Q(2, { qty: null, rangeQty: 1 });
  chk('★本文の数量が読めなければ、今の数量を使う（2本のまま）', p.qty === 2, p);
  chk('範囲と合わないので不一致になる（正しい状態）', p.check === '不一致', p);
  p = Q(2, { qty: 2, rangeQty: 2 });
  chk('本文も範囲も2本なら一致', p.qty === 2 && p.check === '一致', p);
  p = Q(2, { qty: 3, rangeQty: 3 });
  chk('本文から読めたらそちらを使う', p.qty === 3, p);
  p = Q('', { qty: null, rangeQty: 5 });
  chk('今の数量も無ければ範囲を採る（前と同じ）', p.qty === 5 && p.check === 'レンジ採用', p);
}

